/*
 * Role:
 * Define the result values returned by the fixed `cpu_run` integer ABI.
 *
 * Goal:
 * Preserve the existing caller arguments and successful-PC result while making
 * each architecturally relevant interpreter stop distinguishable to host tests
 * and hardware integration. Negative values cannot alias a valid RV32 address.
 */
#define RV32I_STOP_INVALID_INSTRUCTION (-1)
#define RV32I_STOP_ECALL (-2)
#define RV32I_STOP_EBREAK (-3)
#define RV32I_TRAP_INSTRUCTION_ADDRESS_MISALIGNED (-4)
#define RV32I_TRAP_LOAD_STORE_ADDRESS_MISALIGNED (-5)
