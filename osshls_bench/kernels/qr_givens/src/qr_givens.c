#pragma hls toplevel
void qr_givens(const float a[N][N], float r[N][N]) {
    for (size_t i = 0; i < N; ++i) {
        for (size_t j = 0; j < N; ++j) {
            r[i][j] = a[i][j];
        }
    }

    for (size_t j = 0; j < N; ++j) {
        for (size_t i = N - 1; i > j; --i) {
            float a1 = r[i - 1][j];
            float a2 = r[i][j];
            float rnorm = QR_SQRTF(a1 * a1 + a2 * a2);
            float c = a1 / rnorm;
            float s = -a2 / rnorm;
#pragma HLS pipeline
            for (size_t k = j; k < N; ++k) {
                float t1 = c * r[i - 1][k] - s * r[i][k];
                float t2 = s * r[i - 1][k] + c * r[i][k];
                r[i - 1][k] = t1;
                r[i][k] = t2;
            }
        }
    }
}
