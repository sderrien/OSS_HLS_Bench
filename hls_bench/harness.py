"""Generate small tool-specific benchmark harnesses.

Role:
Create deterministic main/testbench sources for runner-specific staging
directories without mutating the benchmark sources in place.

Goal:
Let each tool have its own harness file while keeping the original benchmark
trees unchanged and making generated harnesses easy to inspect in build output.

How:
The module currently focuses on Dynamatic because it needs a verification
wrapper that calls `CALL_KERNEL(...)` from `dynamatic/Integration.h`.  The
generated harness is intentionally conservative: it supports scalar parameters
and fixed-size arrays, and it fails loudly for unsupported pointer/struct-like
signatures rather than guessing.
"""

from __future__ import annotations

from dataclasses import dataclass
import re
from pathlib import Path

from hls_bench import inputs as common_inputs


@dataclass(frozen=True)
class KernelParam:
    """Describe one kernel parameter extracted from a C signature."""

    type_text: str
    name: str
    dimensions: tuple[str, ...]

    @property
    def is_array(self) -> bool:
        return bool(self.dimensions)


@dataclass(frozen=True)
class KernelSignature:
    """Describe the kernel function signature used to generate a harness."""

    return_type: str
    name: str
    params: tuple[KernelParam, ...]


def find_top_signature(source_text: str) -> KernelSignature | None:
    """Extract the first `#pragma HLS top` function signature from a source file."""

    lines = source_text.splitlines()
    func_re = re.compile(
        r"(?P<ret>(?:extern\s+\"C\"\s+)?(?:static\s+)?(?:[A-Za-z_][A-Za-z0-9_:<>]*\s+)*[A-Za-z_][A-Za-z0-9_:<>\*\s]*?)"
        r"\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*\((?P<params>.*?)\)\s*\{",
        re.DOTALL,
    )
    top_line = None
    for idx, line in enumerate(lines):
        lowered = line.lower()
        if (
            "#pragma hls top" in lowered
            or "#pragma hls toplevel" in lowered
            or "#pragma shls top" in lowered
            or "#pragma shls toplevel" in lowered
        ):
            top_line = idx
            break
    search_text = "\n".join(lines[top_line :]) if top_line is not None else source_text
    search_text = re.sub(r'__attribute__\s*\(\(\s*annotate\("hls\.toplevel"\)\s*\)\)\s*', '', search_text)
    match = func_re.search(search_text)
    if match:
        params = tuple(_parse_param(piece) for piece in _split_params(match.group("params")))
        return KernelSignature(
            return_type=match.group("ret").strip(),
            name=match.group("name"),
            params=params,
        )
    return None


def select_integration_header(benchmark_dir: Path, kernel_name: str) -> Path | None:
    """Choose the benchmark-local header most likely needed by the harness."""

    candidates = [benchmark_dir / f"{benchmark_dir.name}.h", benchmark_dir / f"{kernel_name}.h"]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    headers = sorted(benchmark_dir.glob("*.h"))
    return headers[0] if len(headers) == 1 else None


def generate_dynamatic_harness(signature: KernelSignature, header_name: str | None) -> str:
    """Generate a Dynamatic-compatible main() for one kernel signature."""

    shared = common_inputs.get_benchmark_inputs(signature.name)
    if shared is not None:
        return common_inputs.generate_c_harness(shared, use_dynamatic_call=True)

    if signature.name == "spmv":
        return _generate_spmv_harness(signature, header_name)

    lines: list[str] = []
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    if header_name:
        lines.append(f"#include \"{header_name}\"")
    lines.append("#include \"dynamatic/Integration.h\"")
    lines.append("")
    lines.append("// Auto-generated by hls_bench.harness for Dynamatic verification.")
    lines.append("// It provides a deterministic input harness so hls-verifier can")
    lines.append("// record input/output vectors for cycle-accurate simulation.")
    lines.append("")
    lines.append("static unsigned harness_mix(unsigned seed, unsigned salt) {")
    lines.append("  return seed * 1664525u + 1013904223u + salt * 97u;")
    lines.append("}")
    lines.append("")
    for idx, param in enumerate(signature.params):
        if param.is_array:
            lines.extend(_emit_array_initializer(signature.name, idx, param))
            lines.append("")
    lines.append(f"int main(void) {{")
    for idx, param in enumerate(signature.params):
        local_type = _sanitize_type(param.type_text)
        if param.is_array:
            dims = "".join(f"[{dim}]" for dim in param.dimensions)
            lines.append(f"  {local_type} {param.name}{dims};")
            init_name = f"init_{param.name}"
            lines.append(f"  {init_name}({param.name}, {idx + 1}u);")
        else:
            lines.append(f"  {local_type} {param.name} = {_scalar_initializer(local_type, idx + 1)};")
    call_args = ", ".join(p.name for p in signature.params)
    if call_args:
        lines.append(f"  CALL_KERNEL({signature.name}, {call_args});")
    else:
        lines.append(f"  CALL_KERNEL({signature.name});")
    lines.append("  return 0;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _emit_array_initializer(kernel_name: str, idx: int, param: KernelParam) -> list[str]:
    """Emit a dedicated initializer helper for one fixed-size array parameter."""

    type_text = _sanitize_type(param.type_text)
    dims = ", ".join(f"size_t d{i}" for i in range(len(param.dimensions)))
    decl_dims = "".join(f"[{dim}]" for dim in param.dimensions)
    fn_name = f"init_{param.name}"
    out = [f"static void {fn_name}({type_text} {param.name}{decl_dims}, unsigned tag) {{"]
    indent = "  "
    index_names = []
    zero_init = param.name.lower() in {"c", "y", "out", "output", "ref"}
    for dim_idx, dim in enumerate(param.dimensions):
        idx_name = f"i{dim_idx}"
        index_names.append(idx_name)
        out.append(f"{indent}for (size_t {idx_name} = 0; {idx_name} < (size_t)({dim}); ++{idx_name}) {{")
        indent += "  "
    if zero_init:
        out.append(f"{indent}{param.name}" + "".join(f"[{name}]" for name in index_names) + f" = ({type_text})0;")
    else:
        index_expr = " + ".join(f"{name} * {17 * (i + 1)}u" for i, name in enumerate(index_names))
        if not index_expr:
            index_expr = "0u"
        out.append(
            f"{indent}{param.name}" + "".join(f"[{name}]" for name in index_names)
            + f" = ({type_text})harness_mix(tag, {idx + 1}u + ({index_expr}));"
        )
    for _ in param.dimensions[::-1]:
        indent = indent[:-2]
        out.append(f"{indent}}}")
    out.append("}")
    return out


def _parse_param(text: str) -> KernelParam:
    """Parse one C function parameter from a signature string."""

    raw = text.strip()
    dims = tuple(re.findall(r"\[([^\]]+)\]", raw))
    no_dims = re.sub(r"\s*\[[^\]]+\]", "", raw)
    match = re.match(r"^(?P<type>.+?)\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)$", no_dims)
    if not match:
        raise ValueError(f"unsupported parameter syntax: {text!r}")
    type_text = match.group("type").strip()
    name = match.group("name")
    if "*" in type_text:
        raise ValueError(f"pointer parameters are not supported yet: {text!r}")
    return KernelParam(type_text=type_text, name=name, dimensions=dims)


def _split_params(params: str) -> list[str]:
    """Split a parameter list while respecting nested brackets."""

    if not params.strip() or params.strip() == "void":
        return []
    out: list[str] = []
    current: list[str] = []
    depth = 0
    for ch in params:
        if ch == "," and depth == 0:
            piece = "".join(current).strip()
            if piece:
                out.append(piece)
            current = []
            continue
        if ch in "[(":
            depth += 1
        elif ch in ")]":
            depth = max(0, depth - 1)
        current.append(ch)
    piece = "".join(current).strip()
    if piece:
        out.append(piece)
    return out


def _sanitize_type(type_text: str) -> str:
    """Remove qualifiers that would complicate local harness variable declarations."""

    tokens = [token for token in type_text.replace("*", " * ").split() if token not in {"const", "volatile", "restrict"}]
    return " ".join(tokens).replace(" *", "*").replace("* ", "*")


def _scalar_initializer(type_text: str, seed: int) -> str:
    """Return a suitable literal initializer for one scalar harness variable."""

    clean = _sanitize_type(type_text)
    if clean in {"float", "double"}:
        return f"({clean}){seed}.0"
    return f"({clean}){seed}"


def _generate_spmv_harness(signature: KernelSignature, header_name: str | None) -> str:
    """Generate a benchmark-specific harness for the spmv integration test."""

    lines: list[str] = []
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    if header_name:
        lines.append(f"#include \"{header_name}\"")
    lines.append("#include \"dynamatic/Integration.h\"")
    lines.append("")
    lines.append("// Auto-generated by hls_bench.harness for Dynamatic verification.")
    lines.append("// This benchmark uses a fixed sparse-matrix pattern so the runtime")
    lines.append("// harness stays deterministic and the row_ptr array remains valid.")
    lines.append("")
    lines.append("static unsigned harness_mix(unsigned seed, unsigned salt) {")
    lines.append("  return seed * 1664525u + 1013904223u + salt * 97u;")
    lines.append("}")
    lines.append("")
    lines.append("static void init_val(float val[NNZ], unsigned tag) {")
    lines.append("  for (size_t i = 0; i < (size_t)NNZ; ++i)")
    lines.append("    val[i] = ((float)(harness_mix(tag, (unsigned)i + 1u) % 200u) - 100.0f) / 128.0f;")
    lines.append("}")
    lines.append("")
    lines.append("static void init_col(unsigned char col[NNZ], unsigned tag) {")
    lines.append("  (void)tag;")
    lines.append("  for (size_t i = 0; i < (size_t)NNZ; ++i)")
    lines.append("    col[i] = (unsigned char)(i % N);")
    lines.append("}")
    lines.append("")
    lines.append("static void init_row_ptr(unsigned char row_ptr[N + 1], unsigned tag) {")
    lines.append("  (void)tag;")
    lines.append("  unsigned char pattern[N + 1] = {0, 2, 4, 6, 8, 10, 12, 14, 16};")
    lines.append("  for (size_t i = 0; i < (size_t)(N + 1); ++i)")
    lines.append("    row_ptr[i] = pattern[i];")
    lines.append("}")
    lines.append("")
    lines.append("static void init_x(float x[N], unsigned tag) {")
    lines.append("  for (size_t i = 0; i < (size_t)N; ++i)")
    lines.append("    x[i] = ((float)(harness_mix(tag, (unsigned)i + 5u) % 200u) - 100.0f) / 256.0f;")
    lines.append("}")
    lines.append("")
    lines.append("static void init_y(float y[N], unsigned tag) {")
    lines.append("  (void)tag;")
    lines.append("  for (size_t i = 0; i < (size_t)N; ++i)")
    lines.append("    y[i] = 0.0f;")
    lines.append("}")
    lines.append("")
    lines.append("int main(void) {")
    lines.append("  float val[NNZ];")
    lines.append("  init_val(val, 1u);")
    lines.append("  unsigned char col[NNZ];")
    lines.append("  init_col(col, 2u);")
    lines.append("  unsigned char row_ptr[N + 1];")
    lines.append("  init_row_ptr(row_ptr, 3u);")
    lines.append("  float x[N];")
    lines.append("  init_x(x, 4u);")
    lines.append("  float y[N];")
    lines.append("  init_y(y, 5u);")
    lines.append("  CALL_KERNEL(spmv, val, col, row_ptr, x, y);")
    lines.append("  return 0;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)
